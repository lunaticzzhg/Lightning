"""Merge standard domain OpenAPI files and generate transport-only models.

Run: python3.13 scripts/generate_contracts.py [--check]
Each contracts/http/*.openapi.json is a valid standalone OpenAPI 3.1 document.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = ROOT / 'contracts/http'
TARGET = SOURCE_DIR / 'openapi.json'
PY_TARGET = ROOT / 'backend/app/transport.py'
TS_TARGET = ROOT / 'web/infra/transport.ts'


def py_type(spec):
    if '$ref' in spec:
        return spec['$ref'].split('/')[-1]
    typ = spec.get('type')
    if isinstance(typ, list):
        return ' | '.join(py_type({'type': part}) for part in typ)
    if typ == 'array':
        return f"list[{py_type(spec['items'])}]"
    return {'object': 'dict[str, Any]', 'string': 'str', 'integer': 'int', 'number': 'float', 'boolean': 'bool', 'null': 'None'}[typ]


def ts_type(spec):
    if '$ref' in spec:
        return spec['$ref'].split('/')[-1]
    typ = spec.get('type')
    if isinstance(typ, list):
        return ' | '.join(ts_type({'type': part}) for part in typ)
    if typ == 'array':
        return f"{ts_type(spec['items'])}[]"
    return {'object': 'Record<string, unknown>', 'string': 'string', 'integer': 'number', 'number': 'number', 'boolean': 'boolean', 'null': 'null'}[typ]


def build():
    sources = sorted(SOURCE_DIR.glob('*.openapi.json'))
    if not sources:
        raise ValueError('No domain OpenAPI sources found')
    result = {'openapi': '3.1.0', 'info': {'title': 'Lightning management API', 'version': '1.0.0'}, 'paths': {}, 'components': {'schemas': {}}}
    for source in sources:
        doc = json.loads(source.read_text())
        if not doc.get('openapi', '').startswith('3.1.'):
            raise ValueError(f'{source} must be OpenAPI 3.1')
        for path, methods in doc['paths'].items():
            current = result['paths'].setdefault(path, {})
            for method, operation in methods.items():
                if method in current:
                    raise ValueError(f'duplicate operation: {method.upper()} {path}')
                current[method] = operation
        for name, schema in doc.get('components', {}).get('schemas', {}).items():
            current = result['components']['schemas']
            if name in current and current[name] != schema:
                raise ValueError(f'conflicting schema: {name}')
            current[name] = schema
    schemas = result['components']['schemas']
    py = ['# Generated by scripts/generate_contracts.py; do not edit.', 'from __future__ import annotations', 'from typing import Any', 'from pydantic import BaseModel, ConfigDict', '']
    ts = ['// Generated by scripts/generate_contracts.py; do not edit.', '']
    for name, spec in schemas.items():
        py += [f'class {name}(BaseModel):', '    model_config = ConfigDict(extra="forbid")']
        ts += [f'export interface {name} {{']
        required = set(spec.get('required', []))
        for field, field_spec in spec['properties'].items():
            is_required = field in required
            py.append(f'    {field}: {py_type(field_spec)}' + ('' if is_required else ' = None'))
            ts.append(f'  {field}{"" if is_required else "?"}: {ts_type(field_spec)};')
        py.append('')
        ts += ['}', '']
    return {TARGET: json.dumps(result, ensure_ascii=False, indent=2) + '\n', PY_TARGET: '\n'.join(py), TS_TARGET: '\n'.join(ts)}


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs = build()
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'out of date: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print('contracts match' if args.check else 'contracts generated')
